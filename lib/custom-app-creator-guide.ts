  "",
  "Scenario entries include: the online chat output entry, the story mode output entry, the diary generation output entry, and so on. Scenario entries exist to control output format and make the AI understand the current scenario. For example, the Moments-post entry tells the character \"you are using the WeChat Moments feature\" and specifies an output format such as `[朋友圈]...[/朋友圈]`.",
  "",
  "So the final LLM prompt for posting to Moments is structured as: general entries (supplying the character's core persona, worldview, memory, etc.) plus scenario entries (making the AI understand the output scenario and format). The app then post-processes whatever the AI returns.",
  "",
  "The preset system is only used for character output pipelines. Without it, getting a character reply would mean fetching the character's full persona, world books, memory, calendar, user persona, and so on one item at a time, then appending your scenario prompt and sending it all to the LLM. The point of the preset system is that you only write one scenario entry - the character persona, world books, memory, user persona and the rest already live in the presets, so you never have to fetch and assemble them by hand. Call `AiPhone.ai.generate` with the `appTags` of the scenario preset you wrote, and the character automatically picks up the full persona, memory, and so on, then outputs according to that scenario's rules and format.",
  "",
