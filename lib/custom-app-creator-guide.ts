  "**How presets.json participates in the generation pipeline**:",
  "",
  "The phone hosts many apps, regular chats, games, and tools. So that every app can share the user persona, character persona, memory, and so on, the phone has a preset system. It contains **general entries and scenario entries**, and assembles them in the order defined by the preset system. In every app, anything that involves character output goes through the same preset prompt assembly pipeline, which keeps character settings, memory, calendar, and the rest consistent across apps.",
  "",
