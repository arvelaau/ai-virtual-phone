  "",
  "Apps can connect **real people using different accounts**: open a room for realtime play or chat, or use cloud-shared data for asynchronous formats like drift bottles and leaderboards. You must declare the `online.play` permission. Multiplayer is only available on sites where the user **is signed in to a multiplayer account** (standalone mode has no account system, so calls will throw - catch them and tell the user).",
